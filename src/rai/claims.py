"""The claims ledger: every substantive claim in the drafts and its support."""

from __future__ import annotations

import json
from collections import Counter
from typing import Any

from .config import Project
from .store import Store, now

STATUSES = (
    "unchecked",
    "supported",
    "partly supported",
    "contradicted",
    "unsupported",
)


def update_claim(
    store: Store, claim_id: str, status: str, evidence: list[dict[str, Any]]
) -> dict[str, Any]:
    if status not in STATUSES:
        return {"error": f"status must be one of {', '.join(STATUSES)}"}
    row = store.conn.execute("SELECT * FROM claims WHERE id=?", (claim_id,)).fetchone()
    if row is None:
        return {"error": f"No claim {claim_id}."}
    store.conn.execute(
        "UPDATE claims SET status=?, evidence=?, checked_at=? WHERE id=?",
        (status, json.dumps(evidence, ensure_ascii=False), now(), claim_id),
    )
    store.conn.commit()
    render_claims(store.project, store)
    return {"ok": True, "id": claim_id, "status": status}


def claims_for(store: Store, chapter: str | None = None) -> list[Any]:
    sql = "SELECT * FROM claims WHERE active=1"
    args: list[Any] = []
    if chapter:
        sql += " AND chapter=?"
        args.append(chapter)
    return list(store.conn.execute(sql + " ORDER BY chapter, para, id", args))


def summary(store: Store) -> dict[str, Any]:
    rows = claims_for(store)
    by_status = Counter(r["status"] for r in rows)
    uncited_empirical = [
        r["id"] for r in rows if r["type"] == "empirical" and not r["cited"]
    ]
    single_source = []
    for r in rows:
        evidence = json.loads(r["evidence"] or "[]")
        if r["status"] == "supported" and len({e.get("source") for e in evidence}) == 1:
            single_source.append(r["id"])
    return {
        "total": len(rows),
        "by_status": dict(by_status),
        "uncited_empirical": uncited_empirical,
        "contradicted": [r["id"] for r in rows if r["status"] == "contradicted"],
        "single_source": single_source,
    }


def render_claims(project: Project, store: Store) -> str:
    rows = claims_for(store)
    s = summary(store)
    lines = [
        "# Claims ledger",
        "",
        "Generated by rai from the drafts; statuses are set by claim checks.",
        "",
        "## Summary",
        f"- {s['total']} claims: "
        + ", ".join(f"{n} {k}" for k, n in sorted(s["by_status"].items())),
        f"- Uncited empirical claims: {', '.join(s['uncited_empirical']) or 'none'}",
        f"- Contradicted: {', '.join(s['contradicted']) or 'none'}",
        f"- Supported by one source only: {', '.join(s['single_source']) or 'none'}",
        "",
        "## Claims",
        "| ID | Where | Claim | Type | Cited | Status | Evidence |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        evidence = "; ".join(
            f"{e.get('citation', e.get('source', ''))} {e.get('note', '')}".strip()
            for e in json.loads(r["evidence"] or "[]")
        )
        claim = r["claim"].replace("|", "/")
        lines.append(
            f"| {r['id']} | {r['chapter']} para {r['para']} | {claim} | {r['type']} | "
            f"{r['cited'] or '-'} | {r['status']} | {evidence or '-'} |"
        )
    text = "\n".join(lines) + "\n"
    project.claims_path.write_text(text, encoding="utf-8")
    return text
