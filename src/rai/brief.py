"""The shared session briefing, .rai/brief.md, loaded by every agent.

Assembled deterministically from the maps (no model call), so it is cheap to
regenerate after any change.
"""

from __future__ import annotations

import re
from pathlib import Path

from . import ledger
from .cards import read_frontmatter
from .config import Project, estimate_tokens
from .manuscript import draft_files, note_path
from .status import compute

BUDGET_TOKENS = 3000


def _section(text: str, heading: str) -> str:
    match = re.search(
        rf"^#+\s*{re.escape(heading)}\s*$(.*?)(?=^#+\s|\Z)",
        text,
        re.MULTILINE | re.DOTALL | re.IGNORECASE,
    )
    return match.group(1).strip() if match else ""


def _first_paragraph(text: str) -> str:
    for para in re.split(r"\n\s*\n", text):
        para = para.strip()
        if para and not para.startswith("#"):
            return re.sub(r"\s+", " ", para)
    return ""


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def _clip(text: str, limit: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _left_off(project: Project) -> str:
    items = ledger.sessions(project)
    if not items:
        return ""
    last = items[0]
    who = f" with the {last['agent']}" if last["agent"] else ""
    lines = [
        f"## Where we left off\n{last['date']}{who} ({last['id']}): "
        + _clip(last["left_off"] or last["discussed"], 800)
    ]
    if last["understandings"]:
        lines.append(
            "New understandings then:\n"
            + "\n".join(f"- {_clip(u, 200)}" for u in last["understandings"][:5])
        )
    if len(items) > 1:
        lines.append(f'{len(items) - 1} earlier summaries: read_notes("sessions").')
    return "\n".join(lines)


def _decision_section(decisions: list[dict], limit: int) -> str:
    lines = ["## Decisions"]
    for decision in decisions:
        text = _clip(" ".join(decision["text"].split()), limit)
        refs = _clip(" ".join((decision.get("refs") or "").split()), 120)
        lines.append(
            f"- {decision['id']}: {text}" + (f" [{refs}]" if refs else "")
        )
    return "\n".join(lines)


def build_brief(project: Project) -> str:
    project_md = _read(project.project_md)
    thesis = _section(project_md, "Thesis") or _first_paragraph(project_md)
    corpus = _read(project.corpus_dir / "map.md")
    themes = re.findall(r"^### (.+)$", _section(corpus, "Themes"), re.MULTILINE)
    status = compute(project)

    draft_lines = []
    for path in draft_files(project):
        meta, body = read_frontmatter(note_path(project, path))
        first_step = re.search(r"^1\. (.+)$", body, re.MULTILINE)
        line = first_step.group(1) if first_step else "(not mapped yet)"
        draft_lines.append(
            f"- {project.rel(path)} [{meta.get('words', '?')} words]: {line}"
        )

    claims = status.claims
    stale = (
        "- STALE NOTES (treat with care; run `rai refresh`): "
        + _clip(", ".join(status.stale_notes), 600)
        if status.stale_notes
        else "- All notes are current."
    )
    thesis_section = "## Thesis\n" + _clip(
        thesis or "project.md has no thesis yet.", 1200
    )
    draft_section = "## Draft\n" + ("\n".join(draft_lines) or "No draft files yet.")
    parts = [
        f"# Briefing: {project.title or project.name}",
        "Generated by `rai brief`. Maps point, sources prove: confirm anything you "
        "state about a source with read_location before presenting it as fact.",
        thesis_section,
    ]
    draft_index = len(parts)
    parts.append(draft_section)
    parts += [
        "## Library\n"
        + f"{status.sources} sources indexed. "
        + (_first_paragraph(_section(corpus, "Overview")) or "No corpus map yet.")
        + (f"\nThemes: {'; '.join(themes)}." if themes else ""),
        "## State\n"
        + f"- Unresolved objections: {status.open_objections}; "
        + f"decisions recorded: {status.decisions}\n"
        + f"- Claims: {claims.get('total', 0)} total; "
        + ", ".join(f"{n} {k}" for k, n in sorted(claims.get("by_status", {}).items()))
        + f"\n- Uncited empirical claims: {len(claims.get('uncited_empirical', []))}\n"
        + (
            "- Draft citations with no matching source: "
            + ", ".join(status.unknown_citations)
            + "\n"
            if status.unknown_citations
            else ""
        )
        + stale,
    ]
    notes = ledger.notes_state(project)
    active_notes = sum(1 for n in notes.values() if n["status"] == "active")
    deleted_notes = sum(1 for n in notes.values() if n["status"] == "deleted")
    if active_notes or deleted_notes:
        line = f"- {active_notes} active"
        if deleted_notes:
            line += f", {deleted_notes} deleted"
        line += '. read_notes("notes") to survey; search_notes to find one.'
    else:
        line = "- No working notes yet."
    parts.append("## Working notes\n" + line)
    decisions = ledger.list_decisions(project)
    decision_index: int | None = None
    if decisions:
        decision_index = len(parts)
        parts.append(_decision_section(decisions, 240))
    where_index = len(parts)
    parts.append(
        "## Where to look\n"
        "- read_notes: corpus_map, manuscript_map, chapter_note (file=), claims, "
        "objections, decisions, reading, sources, candidates, notes\n"
        "- read_note (id) and search_notes: working notes are prior thinking, "
        "not source evidence\n"
        "- read_card: a source's card\n"
        "- The writer's decisions reach you only through conversation: record "
        "them with the tools as they are made"
    )
    latest = _left_off(project)
    if latest:
        parts.insert(where_index, latest)  # before "Where to look"
    text = "\n\n".join(parts) + "\n"
    while estimate_tokens(text) > BUDGET_TOKENS and draft_lines:
        draft_lines = draft_lines[:-1]
        parts[draft_index] = "## Draft\n" + "\n".join(
            draft_lines + ["- (more in the map)"]
        )
        text = "\n\n".join(parts) + "\n"
    if decision_index is not None:
        for limit in (120, 60):
            if estimate_tokens(text) <= BUDGET_TOKENS:
                break
            parts[decision_index] = _decision_section(decisions, limit)
            text = "\n\n".join(parts) + "\n"
    project.brief_path.parent.mkdir(parents=True, exist_ok=True)
    project.brief_path.write_text(text, encoding="utf-8")
    return text
